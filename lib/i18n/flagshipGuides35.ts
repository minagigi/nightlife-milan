function makeTopicTitle(topic: FlagshipTopicCore, locale: Exclude<LocaleCode, 'en' | 'it'>): string {
  if (locale in topic.titles) {
    return topic.titles[locale as keyof typeof topic.titles];
  }
  const pack = FLAGSHIP_PACKS[locale];
  const focus = topic.focusWord[locale] || topic.focusWord.en;
  return `${focus} ${pack.city} 2026/2027 - ${pack.brand}`;
}

