function makeTopicFaqQ(topic: FlagshipTopicCore, idx: number, locale: Exclude<LocaleCode, 'en' | 'it'>): string {
  if (locale === 'es' || locale === 'fr' || locale === 'de' || locale === 'pt') {
    const arr = topic.faqQuestions[locale];
    if (arr && arr[idx]) return arr[idx];
  }
  const pack = FLAGSHIP_PACKS[locale];
  const focus = topic.focusWord[locale] || topic.focusWord.en;
  const secLabel = (topic.sectionNames[locale] || topic.sectionNames.en)[idx % (topic.sectionNames[locale] || topic.sectionNames.en).length];
  return `${focus} (${pack.city} 2026/2027): ${secLabel}?`;
}

function makeTopicFaqA(topic: FlagshipTopicCore, locale: Exclude<LocaleCode, 'en' | 'it'>): string {
  const pack = FLAGSHIP_PACKS[locale];
  const focus = topic.focusWord[locale] || topic.focusWord.en;
  return `${pack.faqAnswerPrefix} (${focus} - ${pack.city}) ${pack.pricingLead} ${pack.bookingLead} ${pack.ctaLine}`;
}

export function applyFlagshipGuides35(guides: Guide[]): void {
  for (const guide of guides) {
    const topic = FLAGSHIP_TOPICS[guide.id];
    if (!topic) continue;

    // Clean any em-dash on existing EN / IT copy without altering their meaning
    if (guide.title?.en) guide.title.en = stripEmDash(guide.title.en);
    if (guide.title?.it) guide.title.it = stripEmDash(guide.title.it);
    if (guide.excerpt?.en) guide.excerpt.en = stripEmDash(guide.excerpt.en);
    if (guide.excerpt?.it) guide.excerpt.it = stripEmDash(guide.excerpt.it);

    for (const s of guide.sections || []) {
      if (s.heading?.en) s.heading.en = stripEmDash(s.heading.en.replace(/^#+\s*/, ''));
      if (s.heading?.it) s.heading.it = stripEmDash(s.heading.it.replace(/^#+\s*/, ''));
      if (s.content?.en) s.content.en = stripEmDash(s.content.en);
      if (s.content?.it) s.content.it = stripEmDash(s.content.it);
    }
    for (const f of guide.faqs || []) {
      if (f.question?.en) f.question.en = stripEmDash(f.question.en);
      if (f.question?.it) f.question.it = stripEmDash(f.question.it);
      if (f.answer?.en) f.answer.en = stripEmDash(f.answer.en);
      if (f.answer?.it) f.answer.it = stripEmDash(f.answer.it);
    }

    guide.dateModified = '2026-11-13';

    for (const loc of ALL_35_LOCALES) {
      if (loc === 'en' || loc === 'it') continue;
      const tObj = guide.title as Record<string, string>;
      const eObj = guide.excerpt as Record<string, string>;
      tObj[loc] = makeTopicTitle(topic, loc);
      eObj[loc] = makeTopicExcerpt(topic, loc);

      const secTitles = topic.sectionNames[loc] || topic.sectionNames.en;
      (guide.sections || []).forEach((sec, idx) => {
        const name = `${idx + 1}. ${secTitles[idx] || secTitles[idx % secTitles.length]}`;
        (sec.heading as Record<string, string>)[loc] = name;
        (sec.content as Record<string, string>)[loc] = buildLocalizedSectionHtml(topic, name, idx, loc);
      });

      (guide.faqs || []).forEach((faq, idx) => {
        (faq.question as Record<string, string>)[loc] = makeTopicFaqQ(topic, idx, loc);
        (faq.answer as Record<string, string>)[loc] = makeTopicFaqA(topic, loc);
      });
    }
  }
}
