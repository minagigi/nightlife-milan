/** Build a live-calendar formatter payload for one locale on the server. */
export function getHeroTickerCalendar(locale: string): HeroTickerCalendar {
  const enabledLocale = isEnabledLocale(locale) ? locale : 'en';
  const tag = getLocaleDef(enabledLocale)?.hreflang || 'en';
  const options = { timeZone: 'Europe/Rome', weekday: 'short', day: 'numeric', month: 'short' } as const;
  const formatter = new Intl.DateTimeFormat(tag, options);
  const partsFor = (date: Date) => formatter.formatToParts(date);
  const partValue = (date: Date, type: 'weekday' | 'day' | 'month') =>
    partsFor(date).find((part) => part.type === type)?.value || '';
  const referenceSunday = Date.parse('2026-09-06T12:00:00Z');

  return {
    weekdays: Array.from({ length: 7 }, (_, index) => partValue(new Date(referenceSunday + index * 86_400_000), 'weekday')),
    months: Array.from({ length: 12 }, (_, index) => partValue(new Date(Date.UTC(2026, index, 6, 12)), 'month')),
    days: Array.from({ length: 31 }, (_, index) => partValue(new Date(Date.UTC(2026, 0, index + 1, 12)), 'day')),
    pattern: partsFor(new Date(referenceSunday)).flatMap((part): HeroTickerDateToken[] => {
      if (part.type === 'weekday' || part.type === 'day' || part.type === 'month') return [{ type: part.type }];
      return part.type === 'literal' ? [{ type: 'literal', value: part.value }] : [];
    }),
  };
}
