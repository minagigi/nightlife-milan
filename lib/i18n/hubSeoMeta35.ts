export function getHubSeoMeta35(hub: HubKey, locale: string): HubSeoEntry {
  const code = (locale in TITLES[hub] ? locale : 'en') as LocaleCode;
  const title = cleanText(TITLES[hub][code] || TITLES[hub].en);
  const cta = CTA_TAIL[code] || CTA_TAIL.en;
  let description = '';
  if (code === 'en' || code === 'it' || code === 'es' || code === 'fr' || code === 'de' || code === 'pt') {
    description = cleanText(`${DESC_SUMMARY_LEAD[hub][code]} ${cta}`);
  } else {
    const city = CITY_NAME[code] || 'Milan';
    description = cleanText(COMPACT_DESC_TEMPLATE[code](title, city, cta));
  }
  const entry: HubSeoEntry = { title, description };
  if (hub === 'aperitivo') {
    entry.h1 = APERITIVO_H1[code] || APERITIVO_H1.en;
  }
  return entry;
}

export function getAperitivoH1(locale: string): string {
  const code = (locale in APERITIVO_H1 ? locale : 'en') as LocaleCode;
  return APERITIVO_H1[code] || APERITIVO_H1.en;
}
