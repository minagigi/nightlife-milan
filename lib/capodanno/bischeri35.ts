function buildBischeriContent(p: BischeriPack): CapodannoLocalizedEventContent {
  const tiers: CapodannoEventTier[] = [
    { label: p.dinnerLabel, price: p.dinnerPrice, details: p.dinnerDesc },
    { label: p.afterLabel, price: p.afterPrice, details: p.afterDesc },
  ];
  const times = ['20:30', '23:30', '00:00', '00:15'];
  const schedule: CapodannoScheduleStep[] = times.map((time, i) => ({
    time,
    label: p.steps[i],
  }));
  const menus: CapodannoMenuCard[] = [
    {
      id: 'bischeri-terra-140',
      title: p.terraTitle,
      price: p.menuPrice,
      subtitle: p.terraSubtitle,
      beverages: p.beverages,
      courses: p.courseLabels.map((course, idx) => ({ course, dish: p.terraDishes[idx] })),
      imageSrc: TERRA_IMG,
      imageAlt: p.terraAlt,
    },
    {
      id: 'bischeri-mare-140',
      title: p.mareTitle,
      price: p.menuPrice,
      subtitle: p.mareSubtitle,
      beverages: p.beverages,
      courses: p.courseLabels.map((course, idx) => ({ course, dish: p.mareDishes[idx] })),
      imageSrc: MARE_IMG,
      imageAlt: p.mareAlt,
    },
  ];
  return {
    title: p.title,
    subtitle: p.subtitle,
    description: p.description,
    musicAndFormat: p.musicAndFormat,
    dressCode: p.dressCode,
    priceSummary: p.priceSummary,
    tiers,
    highlights: p.highlights,
    sourceBasis: p.sourceBasis,
    scheduleHeading: p.scheduleHeading,
    schedule,
    menusHeading: p.menusHeading,
    menus,
  };
}

