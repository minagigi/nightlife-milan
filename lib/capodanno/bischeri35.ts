  afterPrice: string;
  afterDesc: string;
  highlights: [string, string, string, string];
  sourceBasis: string;
  scheduleHeading: string;
  steps: [string, string, string, string];
  menusHeading: string;
  terraTitle: string;
  mareTitle: string;
  menuPrice: string;
