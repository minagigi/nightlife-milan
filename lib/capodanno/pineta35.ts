function buildPinetaContent(p: PinetaBasePack): CapodannoLocalizedEventContent {
  const tiers: CapodannoEventTier[] = [
    { label: p.tiers.galaLabel, price: p.tiers.galaPrice, details: p.tiers.galaDesc },
    { label: p.tiers.buffetLabel, price: p.tiers.buffetPrice, details: p.tiers.buffetDesc },
    { label: p.tiers.clubLabel, price: p.tiers.clubPrice, details: p.tiers.clubDesc },
    { label: p.tiers.sideLabel, price: p.tiers.sidePrice, details: p.tiers.sideDesc },
    { label: p.tiers.danceLabel, price: p.tiers.dancePrice, details: p.tiers.danceDesc },
    { label: p.tiers.balconyLabel, price: p.tiers.balconyPrice, details: p.tiers.balconyDesc },
    { label: p.tiers.domLabel, price: p.tiers.domPrice, details: p.tiers.domDesc },
    { label: p.tiers.terraceLabel, price: p.tiers.terracePrice, details: p.tiers.terraceDesc },
    { label: p.tiers.vipLabel, price: p.tiers.vipPrice, details: p.tiers.vipDesc },
  ];
  const times = ['20:30', '21:00', '23:00', '23:45', '00:00', '00:15'];
  const schedule: CapodannoScheduleStep[] = times.map((time, i) => ({
    time,
    label: p.menus.steps[i],
  }));
  const menus: CapodannoMenuCard[] = [
    {
      id: 'gala-160',
      title: p.menus.galaTitle,
      price: p.menus.galaPrice,
      subtitle: p.menus.galaSubtitle,
      beverages: p.menus.galaBev,
      courses: p.menus.galaCourses.map(([course, dish]) => ({ course, dish })),
      imageSrc: PINETA_GALA_IMG,
      imageAlt: p.menus.galaAlt,
    },
    {
      id: 'buffet-40',
      title: p.menus.buffetTitle,
      price: p.menus.buffetPrice,
      subtitle: p.menus.buffetSubtitle,
      beverages: p.menus.buffetBev,
      courses: p.menus.buffetCourses.map(([course, dish]) => ({ course, dish })),
      imageSrc: PINETA_BUFFET_IMG,
      imageAlt: p.menus.buffetAlt,
    },
  ];
  return {
    title: p.title,
    subtitle: p.subtitle,
    description: p.description,
    musicAndFormat: p.musicAndFormat,
    dressCode: p.dressCode,
    priceSummary: p.priceSummary,
    tiers,
    highlights: p.highlights,
    sourceBasis: p.sourceBasis,
    scheduleHeading: p.menus.scheduleHeading,
    schedule,
    programImageSrc: PINETA_PROGRAM_IMG,
    menusHeading: p.menus.menusHeading,
    menus,
  };
}

