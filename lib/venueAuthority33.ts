export function buildCityQualifiedVenueH1(
  venue: Venue,
  locale: string,
  localizedVenueName: string,
): string {
  const loc = (CLUB_SERP_35[locale as LocaleCode] ? locale : 'en') as LocaleCode;
  const city = CLUB_SERP_35[loc].city;
  const lower = localizedVenueName.toLowerCase();
  if (
    lower.includes('milan') ||
    lower.includes('milano') ||
    lower.includes(city.toLowerCase())
  ) {
    return localizedVenueName;
  }
  return `${localizedVenueName} ${city}`;
}

