function toRadians(deg: number): number {
  return (deg * Math.PI) / 180;
}

export function haversineMeters(
  lat1: number,
  lon1: number,
  lat2: number,
  lon2: number,
): number {
  const R = 6371000;
  const dLat = toRadians(lat2 - lat1);
  const dLon = toRadians(lon2 - lon1);
  const a =
    Math.sin(dLat / 2) * Math.sin(dLat / 2) +
    Math.cos(toRadians(lat1)) *
      Math.cos(toRadians(lat2)) *
      Math.sin(dLon / 2) *
      Math.sin(dLon / 2);
  return 2 * R * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a));
}

export interface NearbyVenueLink {
  venue: Venue;
  distanceMeters: number;
  distanceLabel: string;
}

export function getRelatedNearbyVenues(
  venue: Venue,
  allVenues: readonly Venue[],
  limit = 6,
): NearbyVenueLink[] {
  const lat1 = venue.coordinates?.latitude ?? 45.4642;
  const lon1 = venue.coordinates?.longitude ?? 9.19;

  return allVenues
    .filter((candidate) => candidate.id !== venue.id)
    .map((candidate) => {
      const lat2 = candidate.coordinates?.latitude ?? 45.4642;
      const lon2 = candidate.coordinates?.longitude ?? 9.19;
      const meters = Math.round(haversineMeters(lat1, lon1, lat2, lon2));
      const distanceLabel =
        meters < 1000 ? `${Math.max(50, Math.round(meters / 10) * 10)} m` : `${(meters / 1000).toFixed(1)} km`;
      return { venue: candidate, distanceMeters: meters, distanceLabel };
    })
    .sort((a, b) => a.distanceMeters - b.distanceMeters)
    .slice(0, limit);
}
