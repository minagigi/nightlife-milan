export function localizeVenueDressCode35(venue: SinglePassVenueSpec, locale: string): string {
  const loc = resolveLocaleCode(locale);
  if (loc === 'it') return venue.dressCodeIt;
  if (loc === 'en') return venue.dressCodeEn;
  const seed = SEEDS_35[loc] || SEEDS_35.en;

  if (venue.id === 'justme' || venue.id === 'voya') {
    return seed.blackTieDress;
  }
  if (venue.id === 'bischeri' || venue.id === 'bobino') {
    return seed.smartChicDress;
  }
  return seed.elegantNyeDress;
}

export function localizeVenueTagline35(
  venue: SinglePassVenueSpec,
  locale: string,
  copy: SinglePassCopyPack,
): string {
  const loc = resolveLocaleCode(locale);
  if (loc === 'it') return venue.taglineIt;
  if (loc === 'en') return venue.taglineEn;
  const ageRange = localizeVenueAgeRange35(venue, loc);
  const music = localizeVenueMusic35(venue, loc);
  const shortCat = copy.venueShortLabels[venue.id];
  return shortCat ? `${ageRange} · ${music}` : `${ageRange} · ${music}`;
}

export function localizeDietaryOptionLabel35(
  opt: { readonly value: string; readonly labelIt: string; readonly labelEn: string },
  locale: string,
): string {
  const loc = resolveLocaleCode(locale);
  if (loc === 'it') return opt.labelIt;
  if (loc === 'en') return opt.labelEn;
  const seed = SEEDS_35[loc] || SEEDS_35.en;

  switch (opt.value) {
    case 'Terra':
      return seed.meatMenu;
    case 'Mare':
      return seed.seaMenu;
    case 'Vegetariano':
      return seed.vegMenu;
    case 'Senza Glutine':
      return seed.gfMenu;
    default:
      return opt.labelEn;
  }
}
