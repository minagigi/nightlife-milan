export function localizeVenueAgeRange35(venue: SinglePassVenueSpec, locale: string): string {
  const loc = resolveLocaleCode(locale);
  if (loc === 'it') return venue.ageBandLabelIt;
  if (loc === 'en') return venue.ageBandLabelEn;
  const seed = SEEDS_35[loc] || SEEDS_35.en;

  const labelByVenue: Partial<Record<SinglePassVenueId, string>> = {
    gate: `18–26 · ${seed.youngLabel}`,
    pineta: `18–29 · ${seed.under30StrictLabel}`,
    repvblic: `22–40 · ${seed.intlCrowdLabel}`,
    justme: `30–49 · ${seed.luxuryCrowdLabel}`,
    bischeri: `50+ · ${seed.over50Label}`,
    bobino: `25–48 · ${seed.dinnerPartyLabel}`,
    voya: `25–50 · ${seed.rooftopLabel}`,
    'justme-garda': `21+ · ${seed.lakeLuxuryLabel}`,
  };

  if (labelByVenue[venue.id]) {
    return labelByVenue[venue.id]!;
  }
  const min = venue.recommendedMinAge;
  const max = venue.strictMaxAge ?? venue.recommendedMaxAge;
  return venue.strictMaxAge ? `${min}–${max}` : `${min}+`;
}

