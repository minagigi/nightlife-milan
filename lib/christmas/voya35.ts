export function christmasVoyaSlug(locale: string): string {
  return CHRISTMAS_VOYA_SLUGS_35[locale as LocaleCode] || CHRISTMAS_VOYA_SLUGS_35.en;
}

export function christmasVoyaPath(locale: string): string {
  const prefix = localePrefix(locale);
  const eventsDir = getLocalizedDir35('events', locale as LocaleCode);
  return `${prefix}/${eventsDir}/${christmasVoyaSlug(locale)}`;
}

export function christmasVoyaHreflangAlternates(baseUrl = 'https://nightlifemilan.com'): Record<string, string> {
  const languages: Record<string, string> = {};
  for (const loc of enabledLocaleCodes) {
    const def = getLocaleDef(loc);
    const key = def?.hreflang || loc;
    languages[key] = `${baseUrl}${christmasVoyaPath(loc)}`;
  }
  languages['x-default'] = `${baseUrl}${christmasVoyaPath('en')}`;
  return languages;
}

export function resolveChristmasVoyaSlug(slug: string): boolean {
  return ALL_CHRISTMAS_SLUGS.has((slug || '').trim().toLowerCase());
}

