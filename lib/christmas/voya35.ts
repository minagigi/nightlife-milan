function buildShortPack(
  loc: LocaleCode,
  metaTitle: string,
  metaDescription: string,
  title: string,
  dateBadge: string,
  priceBadge: string,
  description: string,
  beveragesIncluded: string,
  courses: ChristmasMenuCourse[],
  priceCardAmount: string,
  nyeCrossCta: string,
): ShortChristmasPack {
  const c = CHROME_35[loc];
  const baseTitle = title.split(':')[0].trim();
  const venueAddrLocal = `Viale Achille Papa 30, World Join Center (${c.floor20Label}), 20149 Milano`;
  return {
    metaTitle,
    metaDescription,
    title,
    subtitle: `Voya Rooftop · ${venueAddrLocal} · 25/12/2026`,
    dateBadge,
    priceBadge,
    description,
    scheduleLabel: c.scheduleLabel,
    scheduleValue: `${dateBadge} · ${c.whatsappConcierge247}`,
    dressCodeLabel: c.dressCodeLabel,
    dressCodeValue: c.dressCodeValue,
    tocTitle: `${c.tocIndex} · ${baseTitle}`,
    tocOverview: c.tocOverview,
    tocMenu: c.tocMenu5,
    tocPrice: `${c.tocPrice}: ${priceCardAmount}`,
    tocPayment: c.tocPayment,
    tocBooking: `5. ${c.whatsappConcierge247}`,
    tocMap: c.tocMap,
    tocFaq: c.tocFaq,
    menuHeading: `${baseTitle} · ${c.menuLabel}`,
    menuSubheading: `${dateBadge} · ${beveragesIncluded}`,
    beveragesIncluded,
    courses,
    priceHeading: `${dateBadge} · ${priceCardAmount}`,
    priceCardTitle: `${baseTitle} · Voya Rooftop`,
    priceCardAmount,
    priceCardDetails: beveragesIncluded,
    bookingHeading: c.bookingHeading,
    bookingSubtitle: `${c.whatsappConcierge247} · ${priceCardAmount}`,
    venueBannerEyebrow: c.venueEyebrow,
    venueBannerDesc: venueAddrLocal,
    nyeCrossTitle: c.nyeCrossTitle,
    nyeCrossDesc: c.nyeCrossDescPrefix,
    nyeCrossCta,
    mapHeading: `Google Maps · Viale Achille Papa 30`,
    faqHeading: `${c.tocFaq.replace(/^\d+\.\s*/, '')} · ${baseTitle}`,
    faqs: [
      { q: `${c.highlightPrice} · ${baseTitle} (€)?`, a: `${priceCardAmount}. ${beveragesIncluded}.` },
      { q: `${c.menuLabel} · Voya Rooftop (25/12/2026)?`, a: courses.map((cr) => `${cr.course}: ${cr.dish}`).join(' · ') },
      { q: c.paymentFaqQ, a: c.paymentFaqA },
    ],
  };
}

export function getChristmasVoyaContent(locale: string): ChristmasVoyaContent {
  const data35 = getData35();
  const loc = (locale as LocaleCode) in data35 ? (locale as LocaleCode) : 'en';
  const pack = data35[loc];
  const chrome = CHROME_35[loc];
  const isIt = loc === 'it';
  const addrLocal = `Viale Achille Papa 30, Torre World Join Center (${chrome.floor20Label}), 20149 Milano`;
  return {
    ...pack,
    locationBadge: chrome.locationBadge,
    highlights: [
      `${chrome.highlightVenue}: Voya Rooftop (${addrLocal})`,
      `${chrome.highlightDate}: ${pack.dateBadge}`,
      `${chrome.highlightPrice}: ${pack.priceCardAmount}`,
      pack.beveragesIncluded,
    ],
    posterSrc: '/images/events/christmas-2026-posters/natale-voya-rooftop-milano-2026.webp',
    menuImageSrc: isIt
      ? '/images/events/christmas-2026-menus/voya-natale-2026-menu-it.webp'
      : '/images/events/christmas-2026-menus/voya-natale-2026-menu-en.webp',
  };
}

